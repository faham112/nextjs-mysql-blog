/**
 * Responsive variants for the branded post covers (PageSpeed "Improve image delivery").
 *
 * For every public/covers/posts/<slug>.webp (1200x630) this writes smaller WebPs:
 *   public/covers/posts/w480/<slug>.webp
 *   public/covers/posts/w768/<slug>.webp
 *   public/covers/posts/w960/<slug>.webp
 * and src/lib/coverVariants.generated.ts (slug -> short content hash). The hash is used as a
 * ?v= query on every cover URL, so the files can be cached for a year (immutable) and a
 * regenerated cover still reaches readers immediately.
 *
 * Incremental: a slug is only re-encoded when its 1200px WebP changed (or a variant is missing).
 * Run after scripts/generate-post-covers.mjs (it calls this script at the end):
 *   node scripts/generate-cover-variants.mjs
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "public/covers/posts");
const manifestFile = path.join(root, "src/lib/coverVariants.generated.ts");
export const WIDTHS = [480, 768, 960];

function readManifest() {
  try {
    const txt = fs.readFileSync(manifestFile, "utf8");
    const m = txt.match(/COVER_VERSIONS[^=]*=\s*(\{[\s\S]*?\});/);
    return m ? JSON.parse(m[1]) : {};
  } catch {
    return {};
  }
}

const old = readManifest();
const versions = {};
let made = 0;
const slugs = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".webp"))
  .map((f) => f.slice(0, -5))
  .sort();

for (const slug of slugs) {
  const srcWebp = path.join(dir, `${slug}.webp`);
  const hash = crypto.createHash("sha1").update(fs.readFileSync(srcWebp)).digest("hex").slice(0, 10);
  versions[slug] = hash;
  // Encode from the lossless PNG when present (sharper small sizes), else from the WebP.
  const srcPng = path.join(dir, `${slug}.png`);
  const input = fs.existsSync(srcPng) ? srcPng : srcWebp;
  for (const w of WIDTHS) {
    const out = path.join(dir, `w${w}`, `${slug}.webp`);
    if (old[slug] === hash && fs.existsSync(out)) continue;
    fs.mkdirSync(path.dirname(out), { recursive: true });
    await sharp(input)
      .resize({ width: w, height: Math.round((w * 630) / 1200), fit: "cover" })
      .webp({ quality: 78, effort: 6, smartSubsample: true })
      .toFile(out);
    made++;
  }
}

// Drop variants whose source cover no longer exists.
for (const w of WIDTHS) {
  const d = path.join(dir, `w${w}`);
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d)) {
    if (f.endsWith(".webp") && !versions[f.slice(0, -5)]) fs.unlinkSync(path.join(d, f));
  }
}

const body = `// Generated by scripts/generate-cover-variants.mjs — do not edit by hand.
/** Responsive widths available under public/covers/posts/w<width>/<slug>.webp (plus the 1200px original). */
export const COVER_WIDTHS = ${JSON.stringify(WIDTHS)} as const;

/** slug -> short hash of public/covers/posts/<slug>.webp, used as a ?v= cache-busting query. */
export const COVER_VERSIONS: Record<string, string> = ${JSON.stringify(versions, null, 2)};
`;
fs.writeFileSync(manifestFile, body);
console.log(`cover variants: ${slugs.length} covers, ${made} files written`);
